-- media: one row per uploaded picture. The bytes live in the media bucket (or, in dev, on disk); this is what the rest of the
-- system refers to them by.

-- +goose Up
CREATE TABLE media (
    -- Internal key. Never leaves the service: public_id does.
    id           bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    public_id    uuid        NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    -- "<folder>/<yyyy>/<mm>/<random>.<ext>", made by the service and never reused.
    object_key   text        NOT NULL UNIQUE,
    url          text        NOT NULL,
    folder       text        NOT NULL CHECK (folder IN ('outlets', 'banners', 'vouchers', 'services')),
    file_name    text        NOT NULL DEFAULT '',
    content_type text        NOT NULL,
    size         bigint      NOT NULL CHECK (size > 0),
    width        integer     NOT NULL DEFAULT 0,
    height       integer     NOT NULL DEFAULT 0,
    uploaded_by  text        NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- The gallery lists newest first, optionally one folder; the trailing id breaks ties between uploads of the same instant.
CREATE INDEX media_recent_idx ON media (created_at DESC, id DESC);
CREATE INDEX media_folder_recent_idx ON media (folder, created_at DESC, id DESC);

-- +goose Down
DROP TABLE IF EXISTS media;
