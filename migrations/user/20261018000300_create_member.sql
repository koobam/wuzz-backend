-- member: what a customer holds beyond the account itself — a level earned from
-- xp, a wallet balance and vouchers. The user service owns all of it.
--
-- Points and xp already live on users. There is deliberately no top-up here
-- yet: crediting a wallet belongs to a payment integration that does not exist,
-- so a balance only changes through the ledger below.

-- +goose Up
-- Levels are data, not code: the thresholds are what product decides, so they
-- can be changed with an UPDATE. The rows below are PLACEHOLDER thresholds.
CREATE TABLE member_levels (
    name       text   PRIMARY KEY,
    min_xp     bigint NOT NULL UNIQUE,
    sort_order int    NOT NULL UNIQUE,

    CONSTRAINT member_levels_min_xp_not_negative CHECK (min_xp >= 0)
);

INSERT INTO member_levels (name, min_xp, sort_order) VALUES
    ('Bronze',   0,    1),
    ('Silver',   500,  2),
    ('Gold',     1500, 3),
    ('Platinum', 4000, 4);

-- One row per customer once they have a balance; no row means a balance of zero.
CREATE TABLE wallets (
    user_id    bigint      PRIMARY KEY REFERENCES users (id),
    balance    bigint      NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT wallets_balance_not_negative CHECK (balance >= 0)
);

-- Every change to a balance, signed (credit positive, debit negative). The
-- balance is the sum of these; wallets.balance is kept in step in the same
-- transaction by whatever writes here.
CREATE TABLE wallet_ledger (
    id         bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id    bigint      NOT NULL REFERENCES users (id),
    amount     bigint      NOT NULL,
    kind       text        NOT NULL,
    reference  text        NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT wallet_ledger_amount_nonzero CHECK (amount <> 0)
);

CREATE INDEX wallet_ledger_user_idx ON wallet_ledger (user_id, created_at DESC);

CREATE TABLE vouchers (
    id         bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id    bigint      NOT NULL REFERENCES users (id),
    code       text        NOT NULL,
    title      text        NOT NULL,
    expires_at timestamptz NOT NULL,
    used_at    timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT vouchers_code_not_blank CHECK (code <> '')
);

CREATE UNIQUE INDEX vouchers_user_code_key ON vouchers (user_id, code);
-- Counting a customer's usable vouchers is the hot read.
CREATE INDEX vouchers_user_usable_idx ON vouchers (user_id, expires_at) WHERE used_at IS NULL;

-- +goose Down
DROP TABLE IF EXISTS vouchers;
DROP TABLE IF EXISTS wallet_ledger;
DROP TABLE IF EXISTS wallets;
DROP TABLE IF EXISTS member_levels;
