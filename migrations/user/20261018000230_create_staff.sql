-- People working at an outlet or in the field. Their token's `roles` claim is "outlet:<id>"
-- for front staff and "wuzzer" for a Wuzzer, which the /pos and /station APIs authorise against.
-- outlet_id points into the catalog database, so it cannot be a foreign key here; whether a
-- role needs one (staff_roles.scoped_to_outlet) is checked by the service.

-- +goose Up
CREATE TABLE staff (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    role       text        NOT NULL REFERENCES staff_roles (name),
    outlet_id  bigint,
    status     text        NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT staff_status_valid CHECK (status IN ('active', 'inactive', 'banned')),
    CONSTRAINT staff_phone_format CHECK (phone ~ '^[1-9][0-9]{6,14}$')
);
CREATE UNIQUE INDEX staff_phone_key ON staff (phone);

-- +goose Down
DROP TABLE IF EXISTS staff;
