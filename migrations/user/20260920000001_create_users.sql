-- user: customer accounts. Owned exclusively by the user service; no other
-- service connects to this database.
--
-- A customer is identified by a phone number, proved by a one-time SMS code
-- — there is no password or PIN. `id` is a plain bigint because the mobile
-- client already ships expecting a JSON number for it, not a UUID string.

-- +goose Up
CREATE TABLE users (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username   text        NOT NULL,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    email      text,
    points     bigint      NOT NULL DEFAULT 0,
    streak     bigint      NOT NULL DEFAULT 0,
    xp         bigint      NOT NULL DEFAULT 0,
    birthdate  date,
    status     text        NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT users_status_valid CHECK (status IN ('active', 'inactive', 'banned')),
    CONSTRAINT users_username_format CHECK (username ~ '^[a-z0-9._]{3,20}$'),
    CONSTRAINT users_phone_format CHECK (phone ~ '^[1-9][0-9]{6,14}$'),
    CONSTRAINT users_email_not_blank CHECK (email <> ''),
    CONSTRAINT users_points_not_negative CHECK (points >= 0),
    CONSTRAINT users_streak_not_negative CHECK (streak >= 0),
    CONSTRAINT users_xp_not_negative CHECK (xp >= 0)
);

CREATE UNIQUE INDEX users_username_key ON users (username);
CREATE UNIQUE INDEX users_phone_key ON users (phone);
CREATE UNIQUE INDEX users_email_key ON users (lower(email)) WHERE email IS NOT NULL;

-- +goose Down
DROP TABLE IF EXISTS users;
