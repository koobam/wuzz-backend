-- Back-office and field accounts live in their own tables; `users` is customers only.
--
--   admins  back-office people (finance, support, ...). Sign in to the backoffice.
--   staff   people working at an outlet or in the field: `front` runs the POS of one
--           outlet, `wuzzer` is the technician who is also the driver (station app).
--
-- The kinds of admin and staff are rows in admin_roles / staff_roles, not a CHECK: a new
-- one is an INSERT, with no change to a table. The roles ride in the access token's
-- `roles` claim (admin -> "admin" and "admin:<role>", front -> "outlet:<id>", wuzzer ->
-- "wuzzer"), which is what the /backoffice, /pos and /station APIs authorise against.
-- outlet_id points into the catalog database, so it cannot be a foreign key here.

-- +goose Up
CREATE TABLE admin_roles (name text PRIMARY KEY);
INSERT INTO admin_roles (name) VALUES ('super'), ('finance'), ('support');

CREATE TABLE staff_roles (
    name             text    PRIMARY KEY,
    scoped_to_outlet boolean NOT NULL
);
INSERT INTO staff_roles (name, scoped_to_outlet) VALUES ('front', true), ('wuzzer', false);

CREATE TABLE admins (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    role       text        NOT NULL REFERENCES admin_roles (name),
    status     text        NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT admins_status_valid CHECK (status IN ('active', 'inactive', 'banned')),
    CONSTRAINT admins_phone_format CHECK (phone ~ '^[1-9][0-9]{6,14}$')
);
CREATE UNIQUE INDEX admins_phone_key ON admins (phone);

CREATE TABLE staff (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    role       text        NOT NULL REFERENCES staff_roles (name),
    outlet_id  bigint,
    status     text        NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT staff_status_valid CHECK (status IN ('active', 'inactive', 'banned')),
    CONSTRAINT staff_phone_format CHECK (phone ~ '^[1-9][0-9]{6,14}$')
);
CREATE UNIQUE INDEX staff_phone_key ON staff (phone);

-- +goose Down
DROP TABLE IF EXISTS staff;
DROP TABLE IF EXISTS admins;
DROP TABLE IF EXISTS staff_roles;
DROP TABLE IF EXISTS admin_roles;
