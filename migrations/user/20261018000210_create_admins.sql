-- Back-office people (finance, support, ...). They sign in to the backoffice by phone and
-- one-time code, like every other account. The access token's `roles` claim for an admin is
-- "admin" and "admin:<role>", which is what the /backoffice API authorises against.

-- +goose Up
CREATE TABLE admins (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    phone      text        NOT NULL,
    role       text        NOT NULL REFERENCES admin_roles (name),
    -- The outlet an admin works at when at a till: an admin with one may sign in to the POS, bound to that outlet; without,
    -- the POS refuses them (a till is one outlet's). Points into the catalog database, so it cannot be a foreign key.
    outlet_id  bigint,
    status     text        NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT admins_status_valid CHECK (status IN ('active', 'inactive', 'banned')),
    CONSTRAINT admins_phone_format CHECK (phone ~ '^[1-9][0-9]{6,14}$')
);
CREATE UNIQUE INDEX admins_phone_key ON admins (phone);

-- +goose Down
DROP TABLE IF EXISTS admins;
