-- The options inside a modifier group, each with the price it adds per unit (0 is a free choice).

-- +goose Up
CREATE TABLE modifier_options (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    group_id    bigint      NOT NULL REFERENCES modifier_groups (id) ON DELETE CASCADE,
    name        text        NOT NULL,
    -- A line about it, which the customer app shows under the name.
    description text        NOT NULL DEFAULT '',
    price       bigint      NOT NULL DEFAULT 0,
    -- Whether the option is offered at all.
    active      boolean     NOT NULL DEFAULT true,
    sort_index  integer     NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT modifier_options_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT modifier_options_price_not_negative CHECK (price >= 0)
);

CREATE UNIQUE INDEX modifier_options_group_name_key ON modifier_options (group_id, lower(name));

-- +goose Down
DROP TABLE IF EXISTS modifier_options;
