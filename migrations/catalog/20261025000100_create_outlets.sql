-- catalog: the outlets. Owned exclusively by the catalog service. What the customer app browses (discovery by
-- position, opening hours, pictures) lives here with the outlet it describes.

-- +goose Up
CREATE TABLE outlets (
    id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name           text             NOT NULL,
    address        text             NOT NULL DEFAULT '',
    phone          text             NOT NULL DEFAULT '',
    latitude       double precision NOT NULL DEFAULT 0,
    longitude      double precision NOT NULL DEFAULT 0,
    active         boolean          NOT NULL DEFAULT true,
    category       text             NOT NULL DEFAULT 'all',
    -- Addresses (https) of the outlet's pictures; the first is its banner.
    images         text[]           NOT NULL DEFAULT '{}',
    current_status text             NOT NULL DEFAULT 'quiet',
    delivery_types text[]           NOT NULL DEFAULT '{pickup,delivery}',
    open_time      text             NOT NULL DEFAULT '08:00',
    close_time     text             NOT NULL DEFAULT '22:00',
    version        bigint           NOT NULL DEFAULT 1,
    created_at     timestamptz      NOT NULL DEFAULT now(),
    updated_at     timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT outlets_name_not_blank CHECK (btrim(name) <> '')
);

CREATE INDEX outlets_active_name_idx ON outlets (active, name);

-- +goose Down
DROP TABLE IF EXISTS outlets;
