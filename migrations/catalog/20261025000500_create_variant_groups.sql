-- Variants: the pick-exactly-one choices that define what a service is, such as its speed (Reguler, Express) or a size.
--
-- A group is reusable on purpose: one "Kecepatan" group is stored once and linked to every service that offers it, where
-- a copy per service would be one row to change for each. The name is not unique: two groups may both be called
-- "Kecepatan" because their options price differently, and internal_notes is how an operator tells them apart.

-- +goose Up
CREATE TABLE variant_groups (
    id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name           text        NOT NULL,
    -- A private note for the back office, never shown on the app or the POS.
    internal_notes text        NOT NULL DEFAULT '',
    sort_index     integer     NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT variant_groups_name_not_blank CHECK (btrim(name) <> '')
);

-- +goose Down
DROP TABLE IF EXISTS variant_groups;
