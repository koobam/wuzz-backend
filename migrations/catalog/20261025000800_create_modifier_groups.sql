-- Modifiers: optional add-ons for a service ("Pewangi", "Layanan Tambahan"), as reusable groups with a rule for how many
-- of the options may be picked. Stored once and linked, like the variant groups.

-- +goose Up
CREATE TABLE modifier_groups (
    id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name           text        NOT NULL,
    internal_notes text        NOT NULL DEFAULT '',
    -- The selection rule as two counts. min 0 is an optional group, min >= 1 a required one, min = max "pick exactly N".
    min            integer     NOT NULL DEFAULT 0,
    -- NULL = no ceiling.
    max            integer,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT modifier_groups_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT modifier_groups_min_not_negative CHECK (min >= 0),
    -- A ceiling below the floor, or of zero, would make the group unsatisfiable or pointless.
    CONSTRAINT modifier_groups_max_valid CHECK (max IS NULL OR (max >= 1 AND max >= min))
);

CREATE UNIQUE INDEX modifier_groups_name_key ON modifier_groups (lower(name));

-- +goose Down
DROP TABLE IF EXISTS modifier_groups;
