-- Bill of materials: which materials an owner consumes. The owner is a service, a variant option or a modifier option, so
-- owner_id points at one of three tables and has no foreign key; the app deletes an option's lines when the option goes.
-- Every quantity is in the material's base unit. A material in use cannot be deleted (RESTRICT).

-- +goose Up
CREATE TABLE bom_lines (
    id           bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    owner_type   text          NOT NULL,
    owner_id     bigint        NOT NULL,
    material_id  bigint        NOT NULL REFERENCES materials (id) ON DELETE RESTRICT,
    qty          numeric(18,4) NOT NULL,
    -- unit: used for every unit sold (per kg, per pcs, per session), so it scales with the quantity.
    -- line: used once per order line, whatever the quantity.
    per          text          NOT NULL DEFAULT 'unit',
    -- Standard waste: the effective quantity is qty x (1 + loss_percent / 100).
    loss_percent numeric(6,2)  NOT NULL DEFAULT 0,
    sort_index   integer       NOT NULL DEFAULT 0,
    created_at   timestamptz   NOT NULL DEFAULT now(),
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT bom_lines_owner_type_valid CHECK (owner_type IN ('service', 'variant_option', 'modifier_option')),
    CONSTRAINT bom_lines_qty_positive CHECK (qty > 0),
    CONSTRAINT bom_lines_per_valid CHECK (per IN ('unit', 'line')),
    CONSTRAINT bom_lines_loss_valid CHECK (loss_percent >= 0 AND loss_percent <= 100)
);

CREATE UNIQUE INDEX bom_lines_owner_material_key ON bom_lines (owner_type, owner_id, material_id);
CREATE INDEX bom_lines_owner_idx ON bom_lines (owner_type, owner_id);
CREATE INDEX bom_lines_material_idx ON bom_lines (material_id);

-- +goose Down
DROP TABLE IF EXISTS bom_lines;
