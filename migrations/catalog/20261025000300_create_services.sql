-- catalog: the laundry services the outlets sell. Their variants and modifiers are reusable groups in their own tables
-- (variant_groups, modifier_groups), linked to a service by service_variant_groups and service_modifier_groups.

-- +goose Up
CREATE TABLE services (
    id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name             text             NOT NULL,
    -- kg or pcs for a laundry item; the menu also sells a machine session or a vehicle.
    unit             text             NOT NULL,
    price            bigint           NOT NULL,
    active           boolean          NOT NULL DEFAULT true,
    -- Which category of service_categories it is listed under; NULL = none.
    category_id      bigint REFERENCES service_categories (id) ON DELETE SET NULL,
    description      text             NOT NULL DEFAULT '',
    service_type     text             NOT NULL DEFAULT 'single',
    -- Which menu of the customer app it is in ('regular', 'alacarte'). NULL keeps a service out of the customer app (a
    -- POS-only item). Not the same as category_id, which groups services for staff.
    service_category text,
    min_kg           integer          NOT NULL DEFAULT 0,
    max_kg           integer          NOT NULL DEFAULT 0,
    discount         double precision NOT NULL DEFAULT 0,
    discount_type    text             NOT NULL DEFAULT '',
    icon             text             NOT NULL DEFAULT '',
    image            text             NOT NULL DEFAULT '',
    sort_order       integer          NOT NULL DEFAULT 0,
    version          bigint           NOT NULL DEFAULT 1,
    created_at       timestamptz      NOT NULL DEFAULT now(),
    updated_at       timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT services_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT services_unit_not_blank CHECK (btrim(unit) <> ''),
    CONSTRAINT services_price_not_negative CHECK (price >= 0)
);

CREATE UNIQUE INDEX services_name_key ON services (lower(name));
CREATE INDEX services_menu_idx ON services (service_category, sort_order, id)
    WHERE active AND service_category IS NOT NULL;
CREATE INDEX services_category_idx ON services (category_id);

-- +goose Down
DROP TABLE IF EXISTS services;
