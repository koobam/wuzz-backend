-- catalog: outlets and the laundry services they sell. Owned exclusively by the
-- catalog service.

-- +goose Up
CREATE TABLE outlets (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text             NOT NULL,
    address    text             NOT NULL DEFAULT '',
    phone      text             NOT NULL DEFAULT '',
    latitude   double precision NOT NULL DEFAULT 0,
    longitude  double precision NOT NULL DEFAULT 0,
    active     boolean          NOT NULL DEFAULT true,
    version    bigint           NOT NULL DEFAULT 1,
    created_at timestamptz      NOT NULL DEFAULT now(),
    updated_at timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT outlets_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE services (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    unit       text        NOT NULL,
    price      bigint      NOT NULL,
    active     boolean     NOT NULL DEFAULT true,
    version    bigint      NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT services_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT services_unit_valid CHECK (unit IN ('kg', 'pcs')),
    CONSTRAINT services_price_not_negative CHECK (price >= 0)
);

CREATE UNIQUE INDEX services_name_key ON services (lower(name));

-- +goose Down
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS outlets;
