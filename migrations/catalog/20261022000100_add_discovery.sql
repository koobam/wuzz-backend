-- catalog: what the customer app browses (outlet discovery, the service menu and
-- service areas) now lives next to the data it describes, in Postgres. It used to
-- be a second copy in MongoDB that nothing kept in sync.

-- +goose Up
ALTER TABLE outlets
    ADD COLUMN category       text   NOT NULL DEFAULT 'all',
    ADD COLUMN images         text[] NOT NULL DEFAULT '{}',
    ADD COLUMN current_status text   NOT NULL DEFAULT 'quiet',
    ADD COLUMN delivery_types text[] NOT NULL DEFAULT '{pickup,delivery}',
    ADD COLUMN open_time      text   NOT NULL DEFAULT '08:00',
    ADD COLUMN close_time     text   NOT NULL DEFAULT '22:00';

CREATE INDEX outlets_active_name_idx ON outlets (active, name);

-- The menu uses more units than the POS (a machine session, a vehicle).
ALTER TABLE services DROP CONSTRAINT services_unit_valid;
ALTER TABLE services ADD CONSTRAINT services_unit_not_blank CHECK (btrim(unit) <> '');

ALTER TABLE services
    ADD COLUMN description      text             NOT NULL DEFAULT '',
    ADD COLUMN service_type     text             NOT NULL DEFAULT 'single',
    -- NULL keeps a service out of the customer app (a POS-only item).
    ADD COLUMN service_category text,
    ADD COLUMN min_kg           integer          NOT NULL DEFAULT 0,
    ADD COLUMN max_kg           integer          NOT NULL DEFAULT 0,
    ADD COLUMN discount         double precision NOT NULL DEFAULT 0,
    ADD COLUMN discount_type    text             NOT NULL DEFAULT '',
    ADD COLUMN icon             text             NOT NULL DEFAULT '',
    ADD COLUMN image            text             NOT NULL DEFAULT '',
    ADD COLUMN sort_order       integer          NOT NULL DEFAULT 0,
    ADD COLUMN tiers            jsonb            NOT NULL DEFAULT '[]',
    ADD COLUMN sections         jsonb            NOT NULL DEFAULT '[]';

CREATE INDEX services_menu_idx ON services (service_category, sort_order, id)
    WHERE active AND service_category IS NOT NULL;

-- Regions the service operates in. `geometry` is a GeoJSON Polygon; there are a
-- handful of them, so the service keeps them in memory and tests points itself.
CREATE TABLE coverage_areas (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    geometry   jsonb       NOT NULL,
    active     boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT coverage_areas_name_not_blank CHECK (btrim(name) <> '')
);

-- +goose Down
DROP TABLE IF EXISTS coverage_areas;
DROP INDEX IF EXISTS services_menu_idx;
ALTER TABLE services
    DROP COLUMN sections, DROP COLUMN tiers, DROP COLUMN sort_order, DROP COLUMN image,
    DROP COLUMN icon, DROP COLUMN discount_type, DROP COLUMN discount, DROP COLUMN max_kg,
    DROP COLUMN min_kg, DROP COLUMN service_category, DROP COLUMN service_type,
    DROP COLUMN description;
ALTER TABLE services DROP CONSTRAINT services_unit_not_blank;
ALTER TABLE services ADD CONSTRAINT services_unit_valid CHECK (unit IN ('kg', 'pcs'));
DROP INDEX IF EXISTS outlets_active_name_idx;
ALTER TABLE outlets
    DROP COLUMN close_time, DROP COLUMN open_time, DROP COLUMN delivery_types,
    DROP COLUMN current_status, DROP COLUMN images, DROP COLUMN category;
