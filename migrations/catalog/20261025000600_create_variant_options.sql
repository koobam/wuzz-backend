-- The choices inside a variant group. Choosing one adds its price_delta to the service's price (the first option, the
-- default, is usually 0).

-- +goose Up
CREATE TABLE variant_options (
    id                  bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- CASCADE: an option means nothing without its group.
    group_id            bigint      NOT NULL REFERENCES variant_groups (id) ON DELETE CASCADE,
    name                text        NOT NULL,
    -- Rupiah added per unit to the service's price.
    price_delta         bigint      NOT NULL DEFAULT 0,
    -- The option selected when the choice opens: a variant is required, so there is always one. Exactly one per group.
    is_default          boolean     NOT NULL DEFAULT false,
    -- Whether the option is offered at all; an inactive one stays on old orders but is not shown.
    active              boolean     NOT NULL DEFAULT true,
    sort_index          integer     NOT NULL DEFAULT 0,
    -- How long it takes ("2 hari"), which the customer app shows beside the option; 0 = not stated.
    estimated_time      integer     NOT NULL DEFAULT 0,
    estimated_time_unit text        NOT NULL DEFAULT '',
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT variant_options_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT variant_options_delta_not_negative CHECK (price_delta >= 0),
    CONSTRAINT variant_options_time_not_negative CHECK (estimated_time >= 0)
);

CREATE UNIQUE INDEX variant_options_group_name_key ON variant_options (group_id, lower(name));
CREATE UNIQUE INDEX variant_options_one_default_key ON variant_options (group_id) WHERE is_default;

-- +goose Down
DROP TABLE IF EXISTS variant_options;
