-- catalog: the categories services are grouped in (what the POS filters its service list by). A row here, not a
-- CHECK: a new category is an INSERT. `icon` is the name of an icon the apps know how to draw.

-- +goose Up
CREATE TABLE service_categories (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       text        NOT NULL,
    icon       text        NOT NULL DEFAULT '',
    sort_order integer     NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT service_categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX service_categories_name_key ON service_categories (lower(name));

-- +goose Down
DROP TABLE IF EXISTS service_categories;
