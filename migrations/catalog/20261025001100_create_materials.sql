-- Materials (bahan): what the laundry buys and uses up. Each has a SKU, one base unit that every recipe quantity is in, and
-- the price paid for a given quantity of that unit. What a base unit costs is the exact fraction purchase_price / purchase_qty:
-- it is derived whenever it is needed and never stored, so it is never rounded.

-- +goose Up
CREATE TABLE materials (
    id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sku            text          NOT NULL,
    name           text          NOT NULL,
    category       text          NOT NULL,
    -- The base unit of every quantity of this material.
    unit           text          NOT NULL,
    -- Whole rupiah, buying purchase_qty base units.
    purchase_price bigint        NOT NULL DEFAULT 0,
    purchase_qty   numeric(18,4) NOT NULL,
    active         boolean       NOT NULL DEFAULT true,
    notes          text          NOT NULL DEFAULT '',
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT materials_sku_valid CHECK (sku = btrim(sku) AND char_length(sku) BETWEEN 1 AND 40 AND sku ~ '^[A-Za-z0-9._/-]+$'),
    CONSTRAINT materials_name_valid CHECK (btrim(name) <> '' AND char_length(name) <= 80),
    CONSTRAINT materials_category_valid CHECK (category IN ('chemical', 'packaging', 'consumable', 'other')),
    CONSTRAINT materials_unit_valid CHECK (unit IN ('ml', 'g', 'pcs', 'sheet')),
    CONSTRAINT materials_price_not_negative CHECK (purchase_price >= 0),
    CONSTRAINT materials_qty_positive CHECK (purchase_qty > 0)
);

CREATE UNIQUE INDEX materials_sku_key ON materials (lower(sku));

-- +goose Down
DROP TABLE IF EXISTS materials;
