-- The stock ledger: one immutable row per change of stock. A mistake is corrected by a reversing movement, never by an edit, so
-- UPDATE and DELETE are refused by a trigger. Each row carries the balance after it, which makes the ledger auditable on its own:
-- the value of a balance is always the sum of its value_deltas.
--
-- qty_delta is signed (receipt +, consumption -, waste -, adjustment +/-, transfer_out -, transfer_in +, reversal +).
-- value_delta is signed whole rupiah.

-- +goose Up
CREATE TABLE stock_movements (
    id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    outlet_id       bigint        NOT NULL REFERENCES outlets (id),
    material_id     bigint        NOT NULL REFERENCES materials (id) ON DELETE RESTRICT,
    kind            text          NOT NULL,
    -- waste: expired | damaged | spilled | lost | other; adjustment: count_correction; otherwise empty.
    reason          text          NOT NULL DEFAULT '',
    qty_delta       numeric(18,4) NOT NULL,
    value_delta     bigint        NOT NULL,
    -- The balance after this movement.
    balance_qty     numeric(18,4) NOT NULL,
    balance_value   bigint        NOT NULL,
    ref_type        text          NOT NULL DEFAULT '',
    ref_id          text          NOT NULL DEFAULT '',
    -- The code people know an order by (TRX-25102026-K7M2), kept on the movements made from it so the stock history reads like the Orders
    -- page. ref_id stays the order's id, which is what links a reversal to its consumption. Set when the movement is written and never
    -- changed (the ledger refuses UPDATE).
    ref_code        text,
    supplier        text          NOT NULL DEFAULT '',
    doc_no          text          NOT NULL DEFAULT '',
    note            text          NOT NULL DEFAULT '',
    created_by      text          NOT NULL DEFAULT '',
    created_at      timestamptz   NOT NULL DEFAULT now(),
    -- A retried request carries the same key and gets the original movement back.
    idempotency_key text,
    CONSTRAINT stock_movements_kind_valid CHECK (kind IN ('receipt', 'consumption', 'consumption_reversal', 'waste', 'adjustment', 'transfer_in', 'transfer_out')),
    CONSTRAINT stock_movements_reason_valid CHECK (
        (kind = 'waste' AND reason IN ('expired', 'damaged', 'spilled', 'lost', 'other'))
        OR (kind = 'adjustment' AND reason = 'count_correction')
        OR (kind NOT IN ('waste', 'adjustment') AND reason = '')),
    CONSTRAINT stock_movements_ref_valid CHECK (ref_type IN ('order', 'transfer', '')),
    CONSTRAINT stock_movements_qty_not_zero CHECK (qty_delta <> 0)
);

CREATE UNIQUE INDEX stock_movements_idempotency_key ON stock_movements (outlet_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX stock_movements_outlet_material_idx ON stock_movements (outlet_id, material_id, created_at DESC, id DESC);
CREATE INDEX stock_movements_created_idx ON stock_movements (created_at DESC, id DESC);
CREATE INDEX stock_movements_ref_idx ON stock_movements (ref_type, ref_id) WHERE ref_type <> '';

-- +goose StatementBegin
CREATE FUNCTION stock_movements_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'stock_movements is append-only: record a reversing movement instead';
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER stock_movements_immutable BEFORE UPDATE OR DELETE ON stock_movements
    FOR EACH ROW EXECUTE FUNCTION stock_movements_immutable();

-- +goose Down
DROP TRIGGER IF EXISTS stock_movements_immutable ON stock_movements;
DROP FUNCTION IF EXISTS stock_movements_immutable();
DROP TABLE IF EXISTS stock_movements;
