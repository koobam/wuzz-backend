-- People who left their email on the public landing page (wuzz.care) to hear about the launch. One row per address: signing up twice
-- is not an error and does not add a second row. The address is stored lower-cased.

-- +goose Up
CREATE TABLE waitlist (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email      text        NOT NULL,
    -- The language the page was shown in (id | en), so the launch mail can go out in it.
    language   text        NOT NULL DEFAULT 'id',
    -- Which page collected it.
    source     text        NOT NULL DEFAULT 'landing',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT waitlist_email_unique UNIQUE (email),
    CONSTRAINT waitlist_email_shape CHECK (email = lower(email) AND length(email) <= 254),
    CONSTRAINT waitlist_language_valid CHECK (language IN ('id', 'en'))
);

CREATE INDEX waitlist_created_idx ON waitlist (created_at DESC, id DESC);

-- +goose Down
DROP TABLE IF EXISTS waitlist;
