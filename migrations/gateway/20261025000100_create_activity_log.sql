-- The activity log: one immutable row per state-changing thing done through the back office or the POS (a service created, a stock
-- count adjusted, an order moved on, someone signed in). A mistake is corrected by the next action, never by editing the log, so
-- UPDATE and DELETE are refused by a trigger, like the stock ledger.
--
-- Written by the gateway, after the response, from the route that was called: the actor comes from the access token, the entity from
-- the route (or from the answer, for a create), `changes` is the request body with secrets removed. summary_key/summary_params are what
-- the apps translate into a sentence ("activity.service.create" with {"name": "Cuci Kiloan"}).

-- +goose Up
CREATE TABLE activity_log (
    id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at     timestamptz NOT NULL DEFAULT now(),
    -- backoffice | pos | station
    audience       text        NOT NULL,
    -- Who did it. Empty only for a sign-in that failed: nobody was identified.
    actor_id       text        NOT NULL DEFAULT '',
    actor_name     text        NOT NULL DEFAULT '',
    actor_roles    text[]      NOT NULL DEFAULT '{}',
    -- create | update | delete | status | receive | waste | adjust | transfer | set_min | sign_in | sign_out
    action         text        NOT NULL,
    -- outlet | service | variant_group | modifier_group | material | bom | stock | order | user | session
    entity_type    text        NOT NULL,
    entity_id      text        NOT NULL DEFAULT '',
    summary_key    text        NOT NULL,
    summary_params jsonb       NOT NULL DEFAULT '{}'::jsonb,
    -- The request body, secrets removed and long values cut; NULL when there was none worth keeping.
    changes        jsonb,
    -- ok | failed (the request was refused or broke; status says how)
    outcome        text        NOT NULL,
    status         integer     NOT NULL,
    request_id     text        NOT NULL DEFAULT '',
    ip             text        NOT NULL DEFAULT '',
    CONSTRAINT activity_log_outcome_valid CHECK (outcome IN ('ok', 'failed'))
);

CREATE INDEX activity_log_created_idx ON activity_log (created_at DESC, id DESC);
CREATE INDEX activity_log_entity_idx ON activity_log (entity_type, entity_id, created_at DESC, id DESC);
CREATE INDEX activity_log_actor_idx ON activity_log (actor_id, created_at DESC, id DESC) WHERE actor_id <> '';

-- +goose StatementBegin
CREATE FUNCTION activity_log_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'activity_log is append-only';
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER activity_log_immutable BEFORE UPDATE OR DELETE ON activity_log
    FOR EACH ROW EXECUTE FUNCTION activity_log_immutable();

-- +goose Down
DROP TRIGGER IF EXISTS activity_log_immutable ON activity_log;
DROP FUNCTION IF EXISTS activity_log_immutable();
DROP TABLE IF EXISTS activity_log;
